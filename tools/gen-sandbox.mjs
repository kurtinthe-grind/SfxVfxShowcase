const BASE = { anchor: mod.UIAnchor.TopLeft, visible: true, parent: null, depth: mod.UIDepth.AboveGameUI, receiver: {} };

function add(n, ox, oy, fields, scope) {
  let w = n.w ?? 0;
  if (n.wScale !== undefined) w = w * Number(prop(n, n.wScale, fields, scope) ?? 0);

  const common = {
    ...BASE,
    position: { x: ox + n.x, y: oy + n.y },
    size: { width: Math.max(0, w), height: n.h ?? 0 },
    bgColor: hexToVec(prop(n, "bg", fields, scope) ?? "#000000"),
    bgAlpha: Number(prop(n, "bgAlpha", fields, scope) ?? 1),
    bgFill: FILL[prop(n, "fill", fields, scope)] ?? mod.UIBgFill.None,
  };

  if (n.k === "container") return new UIContainer(common);

  const tSize = Number(prop(n, "textSize", fields, scope) ?? 7);
  const tColor = hexToVec(prop(n, n.k === "text" ? "color" : "textColor", fields, scope) ?? "#FFFFFF");
  const tAnchor = ANCHOR[prop(n, "align", fields, scope)] ?? mod.UIAnchor.Center;

  if (n.k === "text") {
    return new UIText({ ...common, message: prop(n, "text", fields, scope) ?? "", textSize: tSize, textColor: tColor, textAlpha: Number(prop(n, "textAlpha", fields, scope) ?? 1), textAnchor: tAnchor, wrap: n.wrap === true });
  }
  const isText = n.k === "textbutton";
  return new (isText ? UITextButton : UIButton)({
    ...common,
    message: isText ? prop(n, "text", fields, scope) ?? "" : "",
    textSize: tSize, textColor: tColor, textAnchor: tAnchor,
    baseColor: hexToVec(prop(n, "bg", fields, scope) ?? "#000000"),
    baseAlpha: Number(prop(n, "bgAlpha", fields, scope) ?? 1),
    enabled: n.enabled !== false,
  });
}

function walk(nodes, ox, oy, fields, scope) {
  const groupVisible = {};
  // A group may carry its own origin; children are relative to it.
  const groupOrigin = {};
  for (let i = 0; i < nodes.length; i++) {
    const n = nodes[i];
    if (n.k === "group") {
      // A group nested inside a hidden group is itself hidden. buildNodes() in
      // ui.ts gets this from recursion; walk() is flat, so it has to check.
      const id = n.id ?? "g" + i;
      if (n.parent !== undefined && groupVisible[n.parent] === false) {
        groupVisible[id] = false;
        groupOrigin[id] = { x: 0, y: 0 };
        continue;
      }
      const bound = prop(n, "visible", fields, scope);
      groupVisible[id] = bound !== undefined ? bound !== "0" : n.visible !== false;
      groupOrigin[id] = { x: n.x, y: n.y };
      continue;
    }
    let gx = 0, gy = 0;
    if (n.parent !== undefined) {
      if (groupVisible[n.parent] === false) continue;
      const o = groupOrigin[n.parent];
      if (o) { gx = o.x; gy = o.y; }
    }

    if (n.k === "repeat") {
      const tpl = n.template;
      if (!tpl) continue;
      const count = n.count ?? 0, cols = n.cols ?? 0, gap = n.gap ?? 0;
      const gapX = n.gapX ?? gap, gapY = n.gapY ?? gap;
      const tw = tpl.w ?? 0, th = tpl.h ?? 0;
      for (let j = 0; j < count; j++) {
        const cx = cols > 0 ? (j % cols) * (tw + gapX) : j * (tw + gap);
        const cy = cols > 0 ? Math.floor(j / cols) * (th + gapY) : 0;
        add({ ...tpl, x: tpl.x + cx, y: tpl.y + cy }, ox + gx + n.x, oy + gy + n.y, fields, scope);
      }
      continue;
    }
    add(n, ox + gx, oy + gy, fields, scope);
  }
}

