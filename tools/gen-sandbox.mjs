function copyPreviewTool() {
    if (!existsSync(TOOL)) {
        console.warn(`  WARNING: preview tool not found at ${TOOL}; skipped copy.`);
        return;
    }
    for (const f of ["index.html", "server.mjs"]) copyFileSync(resolve(TOOL, f), resolve(PREVIEW, f));

    // The upstream index.html opens a long-lived SSE connection for hot reload,
    // which stops headless Chrome/Edge from ever reaching network idle, so
    // --screenshot hangs forever. Re-apply the ?nohot=1 gate after every copy.
    const idx = resolve(PREVIEW, "index.html");
    let html = readFileSync(idx, "utf8");
    const anchor = '        const sse = new EventSource("/__reload");';
    if (html.includes(anchor) && !html.includes("nohot")) {
        html = html.replace(
            anchor,
            '        if (new URLSearchParams(location.search).get("nohot") === "1") return;\n' + anchor
        );
        writeFileSync(idx, html, "utf8");
        console.log("  index.html: re-applied ?nohot=1 gate (needed for headless screenshots)");
    }
    mkdirSync(resolve(PREVIEW, "src"), { recursive: true });
    if (!existsSync(resolve(PREVIEW, "src", "renderer.js"))) copyFileSync(resolve(TOOL, "src", "renderer.js"), resolve(PREVIEW, "src", "renderer.js"));
    const assets = resolve(TOOL, "assets");
    if (existsSync(assets)) {
        mkdirSync(resolve(PREVIEW, "assets"), { recursive: true });
        for (const f of readdirSync(assets)) copyFileSync(resolve(assets, f), resolve(PREVIEW, "assets", f));
    }
    patchRenderer();
    console.log("  preview tool synced");
}

// The upstream renderer's UIText never applies params.textSize, while
// UITextButton does. That makes every plain-text element render at browser
// default size regardless of the layout, which silently invalidates any type
// tuning done against the preview. Re-apply the fix after every copy.
function patchRenderer() {
    const rp = resolve(PREVIEW, "src", "renderer.js");
    if (!existsSync(rp)) return;
    let src = readFileSync(rp, "utf8");
    if (src.includes("TEXT_SIZE_PATCH")) return;
    const target = `    s.fontFamily = "'BF Text', 'Segoe UI', 'Arial Narrow', sans-serif";\n    s.letterSpacing = "0.5px";`;
    const patched = `    s.fontFamily = "'BF Text', 'Segoe UI', 'Arial Narrow', sans-serif";\n    // TEXT_SIZE_PATCH: UIText honoured textSize like UITextButton already did.\n    if (params.textSize) s.fontSize = params.textSize + "px";\n    s.letterSpacing = "0.5px";`;
    if (!src.includes(target)) {
        console.warn("  WARNING: renderer.js patch anchor not found; UIText will ignore textSize.");
        return;
    }
    src = src.replace(target, patched);

    // Also: UITextButton hardcodes justifyContent/alignItems to centre, so
    // textAnchor is ignored and every button label centres regardless. Make it
    // honour the anchor the same way UIText does.
    const btnAnchorTarget = `    s.justifyContent = "center";\n    s.textAlign = "center";\n    s.fontFamily = "'BF Text', 'Segoe UI', 'Arial Narrow', sans-serif";\n    s.fontWeight = "700";`;
    const btnAnchorPatched = `    s.justifyContent = "center";\n    s.textAlign = "center";\n    s.fontFamily = "'BF Text', 'Segoe UI', 'Arial Narrow', sans-serif";\n    s.fontWeight = "700";\n    // TEXT_ANCHOR_PATCH\n    if (params.textAnchor) {\n      const ta = params.textAnchor;\n      if (ta.includes("Left")) s.justifyContent = "flex-start";\n      else if (ta.includes("Right")) s.justifyContent = "flex-end";\n      if (ta.includes("Top")) s.alignItems = "flex-start";\n      else if (ta.includes("Bottom")) s.alignItems = "flex-end";\n    }`;
    if (src.includes(btnAnchorTarget)) src = src.replace(btnAnchorTarget, btnAnchorPatched);
    writeFileSync(rp, src, "utf8");
    console.log("  renderer.js: UIText honours textSize; UITextButton honours textAnchor");
}
