function trunc(s, max) { return s.length <= max ? s : s.slice(0, max - 1) + "\\u2026"; }

function resolveToken(tok, fields) {
  const body = tok.slice(2, tok.length - 2);
  const dot = body.indexOf(".");
  if (dot < 0) return body;
  const g = fields[body.slice(0, dot)];
  if (g === undefined) return body;
  const v = g[body.slice(dot + 1)];
  return v === undefined ? body : String(v);
}

function prop(n, key, fields, scope) {
  if (n.bind && n.bind[key] !== undefined) {
    const s = fields[scope];
    if (s !== undefined && s[n.bind[key]] !== undefined) return String(s[n.bind[key]]);
  }
  const raw = n[key];
  if (raw === undefined) return undefined;
  return typeof raw === "string" && raw.startsWith("{{") ? resolveToken(raw, fields) : String(raw);
}

